def _identity_house_groups(c):
    groups = {i: [] for i in range(1, 13)}
    for name, house in c.get("houses", {}).items():
        if name in c.get("planets", {}):
            groups.setdefault(house, []).append(name)
    return groups

def _identity_house_score(names):
    w = {
        "Солнце": 5, "Луна": 5, "Меркурий": 3, "Венера": 3, "Марс": 3,
        "Юпитер": 2, "Сатурн": 2, "Уран": 1, "Нептун": 1, "Плутон": 1,
        "Северный узел": 2, "Южный узел": 2,
    }
    return sum(w.get(x, 1) for x in names) + max(0, len(names)-2)*2

def _identity_dominant_houses(c):
    groups = _identity_house_groups(c)
    ranked = sorted(
        [(_identity_house_score(names), house, names) for house, names in groups.items() if names],
        key=lambda x: (x[0], len(x[2])),
        reverse=True
    )
    stelliums = [x for x in ranked if len(x[2]) >= 3]
    return (stelliums or ranked)[:2]

