def pair_aspect(c, one, two):
    """Return the strongest whole-sign aspect between two planets, if present."""
    for a in meaningful_aspects(c,[one,two],12):
        if {a["a"],a["b"]} == {one,two}:
            return a
    return None


def family_signature(c):
    """IV-house biography in everyday language. Concrete claims require corroboration and remain probabilistic."""
    h=c["houses"]
    mp=pair_aspect(c,"Луна","Плутон"); ms=pair_aspect(c,"Луна","Сатурн")
    moon4=h.get("Луна")==4; mars4=h.get("Марс")==4; sat4=h.get("Сатурн")==4; pl4=h.get("Плутон")==4
    pieces=[]
    if moon4:
        pieces.append("Дом и семейная атмосфера в детстве могли особенно сильно влиять на твоё настроение и чувство безопасности: происходящее между близкими трудно было просто оставить за дверью комнаты.")
    if moon4 and mp and mp["aspect"] in TENSION:
        pieces.append("При напряжении Луны с Плутоном мама могла быть эмоционально прохладной, контролирующей или сама жить в сильном напряжении. Возможен и другой бытовой сценарий: ребёнка рано посвящали во взрослые переживания, конфликты или проблемы семьи, поэтому внутренне приходилось взрослеть раньше времени.")
    elif moon4 and ms and ms["aspect"] in TENSION:
        pieces.append("Напряжение Луны с Сатурном часто делает домашнюю эмоциональную среду более сдержанной: тепла могло ощущаться меньше, чем хотелось, а от ребёнка могли ждать взрослости, собранности или умения не создавать дополнительных проблем.")
    if mars4:
        pieces.append("Марс в IV доме добавляет динамику: дома могли быть споры, повышенные тона, резкие выяснения отношений или ситуации, где приходилось защищать себя и своё пространство. В более конструктивном варианте это очень деятельная семья — много движения, переездов, ремонтов и постоянных дел.")
