def _child_house_strength(c):
    weights={"Солнце":3,"Луна":2,"Меркурий":2,"Венера":1.5,"Марс":2,"Юпитер":2,"Сатурн":2,"Уран":1,"Нептун":1,"Плутон":1}
    score={i:0 for i in range(1,13)}
    for n,w in weights.items():
        if n in c["houses"]: score[c["houses"][n]]+=w
    score[c["houses"][c["asc_ruler"]]]+=2; score[c["houses"][c["sun_dispositor"]]]+=2
    return sorted(score,key=lambda x:(-score[x],x)),score


