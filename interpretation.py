def technical(c):
    ps=c["planets"]; lines=["🔧 ТЕХНИЧЕСКАЯ КАРТА",""]
    lines += [f"ASC {c['asc'].sign} {fmtdeg(c['asc'].degree)} | MC {c['mc'].sign} {fmtdeg(c['mc'].degree)}"]
    for n,p in ps.items(): lines.append(f"{n}: {p.sign} {fmtdeg(p.degree)}, дом {c['houses'][n]}")
    lines += ["","Куспиды Placidus:"]
    for i,x in enumerate(c["cusps"],1): lines.append(f"{i}: {SIGNS[int(x//30)]} {fmtdeg(x%30)}")
