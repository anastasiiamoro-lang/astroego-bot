def repeated_sign(c,names):
    groups={}
    for n in names:
        s=c["planets"][n].sign
        groups.setdefault(s,[]).append(n)
    return {s:v for s,v in groups.items() if len(v)>1}

def meaningful_aspects(c,names,limit=4):
    return strongest(c,names,limit)

