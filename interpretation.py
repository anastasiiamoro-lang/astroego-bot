def current_report(natal,transit):
    # compare transit planets to natal planets using sign relationship + exactness
    from astro_engine import whole_sign_aspect, orb_for, strength
    rows=[]
    for tn,tp in transit["planets"].items():
        for nn,np in natal["planets"].items():
            asp=whole_sign_aspect(tp,np)
            if asp:
                o=orb_for(tp,np,asp); lab,r=strength(tn,o)
                rows.append((r,o,tn,nn,asp,natal["houses"][nn]))
    rows.sort()
    top=rows[:5]
    lines=["🕰 ЧТО ПРОИСХОДИТ СЕЙЧАС",""]
    if not top: return "\n".join(lines+["Сейчас нет ярко выделенного аспекта в нашей основной системе."])
    for _,o,tn,nn,asp,house in top:
        lines.append(f"Сейчас тема «{PLANET_DRIVE.get(tn,tn)}» особенно затрагивает твою натальную функцию «{PLANET_DRIVE.get(nn,nn)}». Это проявляется через сферу «{HOUSE_LIFE[house]}».")
    lines += ["","Смысл этого раздела — не предсказать событие любой ценой, а показать, какая часть твоей жизни сейчас требует больше внимания и осознанного действия."]
    return "\n".join(lines)

