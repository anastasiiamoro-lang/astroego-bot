def emphasized_houses(c, minimum=3):
    counts={}
    for name,house in c.get("houses",{}).items():
        if name in c.get("planets",{}): counts[house]=counts.get(house,0)+1
    return sorted([(h,n) for h,n in counts.items() if n>=minimum], key=lambda x:(-x[1],x[0]))


